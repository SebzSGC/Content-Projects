export function buildTranscriptFromText(
  text: string,
  startOffsetSec = 0
): TranscriptWord[] {
  const rawTokens = text
    .split(/\s+/)
    .filter((tok) => tok && !tok.includes("pause") && !tok.includes("___"));
  let cursor = startOffsetSec;
  return rawTokens.map((tok, index) => {
    const clean = tok.replace(/[.,!?;:"]/g, "").toLowerCase();
    const isFiller = clean === "um" || clean === "uh" || clean === "like";
    const duration = Math.max(0.24, Math.min(0.55, tok.length * 0.055));
    const start = Number(cursor.toFixed(2));
    const end = Number((cursor + duration).toFixed(2));
    cursor = end + 0.04;

    let highlight: "none" | "color1" | "color2" = "none";
    if (
      ["million", "secret", "viral", "ai", "attention", "hook", "10x", "city", "game-winner", "retention"].includes(
        clean
      )
    ) {
      highlight = "color1";
    } else if (
      ["never", "first", "framework", "money", "mistake", "three", "revenue", "builder"].includes(
        clean
      )
    ) {
      highlight = "color2";
    }

    const emojiMap: Record<string, string> = {
      million: "💰",
      viral: "🔥",
      ai: "⚡",
      hook: "🎯",
      city: "🏙️",
      "game-winner": "🏀",
      retention: "📈",
    };

    return {
      id: `w-${index}`,
      word: tok,
      start,
      end,
      isFiller,
      isPause: false,
      deleted: false,
      highlight,
      emoji: emojiMap[clean],
      speaker: index % 18 < 12 ? "Speaker 1" : "Speaker 2",
    };
  });
}

